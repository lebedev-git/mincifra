"use strict";
// Генерация документов ОТЧУЖДЕНИЯ исключительного права (Схема B, ст. 1234 ГК РФ):
// автор-физлицо, на которого оформлено депонирование ПрЭВМ, передаёт исключительное
// право организации-правообладателю (ООО). Без этого шага цепочка прав рвётся и
// заявку в реестр Минцифры завернут.
//
// listAssignmentDocs() -> [{ kind, title, file, make(product, ctx) }]
//   ctx.author  — данные автора-физлица из профиля (ФИО, дата рожд., СНИЛС, адрес).
//   Реквизиты приобретателя (ООО) и № свидетельства берутся из карточки продукта.
//
// ВНИМАНИЕ: правовые формулировки — шаблонные каркасы, проверяет юрист правообладателя.

const H = require("./lib/docx_helpers");
const { H1, P, bullet, R, B, sp, pageBreak, note, tbl, titleBlock, buildBuffer } = H;

function today() {
  const d = new Date();
  return `${String(d.getDate()).padStart(2, "0")}.${String(d.getMonth() + 1).padStart(2, "0")}.${d.getFullYear()}`;
}
function safeFileName(s) {
  return String(s || "").replace(/[<>:"/\\|?*\x00-\x1F]/g, "").replace(/\s+/g, " ").trim();
}
function val(x, dash = "____") { return (x === undefined || x === null || x === "") ? dash : String(x); }

// Строка идентификации свидетельства ПрЭВМ (основание возникновения права у автора).
function certLine(r) {
  const num = val(r.rospatentCertificateNumber);
  const date = val(r.rospatentCertificateDate);
  return `свидетельство о государственной регистрации программы для ЭВМ № ${num} от ${date}`;
}

// ---------- Договор отчуждения исключительного права ----------
function docContract(pr, ctx = {}) {
  const p = pr.product || {}, rh = pr.rightholder || {}, r = pr.rights || {};
  const a = ctx.author || {};
  const c = [];
  c.push(...titleBlock("ДОГОВОР",
    "об отчуждении исключительного права на программу для ЭВМ (ст. 1234 ГК РФ)",
    [`Программа: ${val(p.name)}`, `Дата: ${today()}`]));
  c.push(sp(160));

  c.push(P([
    B("Правообладатель (Автор): "),
    R(`${val(a.fullName)}, `),
    R(a.birthDate ? `дата рождения ${a.birthDate}, ` : ""),
    R(a.citizenship ? `гражданство ${a.citizenship}, ` : ""),
    R(a.snils ? `СНИЛС ${a.snils}, ` : ""),
    R(`адрес: ${val(a.address)}`),
    R(", с одной стороны, и"),
  ]));
  c.push(P([
    B("Приобретатель: "),
    R(`${val(rh.orgName)} (ОГРН ${val(rh.ogrn)}, ИНН ${val(rh.inn)}, адрес: ${val(rh.address)}), `),
    R("в лице "),
    R(rh.signatory && rh.signatory.name ? `${rh.signatory.position || "руководителя"} ${rh.signatory.name}` : "уполномоченного лица"),
    R(", с другой стороны, заключили настоящий договор о нижеследующем."),
  ]));
  c.push(sp());

  c.push(H1("1. Предмет договора"));
  c.push(P([R("1.1. Автор передаёт (отчуждает) Приобретателю в полном объёме исключительное право на программу для ЭВМ "),
    B(val(p.name)), R(" (далее — Программа).")]));
  c.push(P([R("1.2. Исключительное право Автора на Программу подтверждается: "), R(certLine(r)), R(".")]));
  c.push(P([R("1.3. Исключительное право переходит к Приобретателю в момент подписания настоящего договора в полном объёме и без ограничений по территории и сроку (п. 1 ст. 1234 ГК РФ).")]));
  c.push(sp());

  c.push(H1("2. Вознаграждение"));
  c.push(P([R("2.1. За отчуждение исключительного права Приобретатель выплачивает Автору вознаграждение в размере "),
    B("__________ руб."), R(" в срок до «__» ________ 20__ г.")]));
  c.push(P([R("2.2. Стороны вправе предусмотреть безвозмездность, если это прямо допускается (с учётом ограничений п. 3.1 ст. 1234 ГК РФ).")]));
  c.push(sp());

  c.push(H1("3. Гарантии"));
  c.push(bullet("Автор гарантирует, что является единственным обладателем отчуждаемого исключительного права и оно не обременено правами третьих лиц."));
  c.push(bullet("Программа не нарушает исключительных прав третьих лиц."));
  c.push(sp());

  c.push(H1("4. Заключительные положения"));
  c.push(P([R("4.1. Договор вступает в силу с момента подписания. Передача Программы оформляется актом приёма-передачи.")]));
  c.push(sp(240));

  c.push(tbl([4680, 4680], ["Автор", "Приобретатель"], [
    [`${val(a.fullName)}\n\n_______________ / подпись`,
     `${val(rh.orgName)}\n${rh.signatory && rh.signatory.name ? rh.signatory.name : "___________________"}\n\n_______________ / М.П.`],
  ]));
  c.push(sp());
  c.push(note("Дисклеймер", [R("Каркас договора по ст. 1234 ГК РФ. Проверить и подписать у юриста правообладателя. Вознаграждение и порядок оплаты — согласовать сторонами.")]));
  return c;
}

// ---------- Акт приёма-передачи ----------
function docAct(pr, ctx = {}) {
  const p = pr.product || {}, rh = pr.rightholder || {}, r = pr.rights || {};
  const a = ctx.author || {};
  const c = [];
  c.push(...titleBlock("АКТ",
    "приёма-передачи по договору об отчуждении исключительного права",
    [`Программа: ${val(p.name)}`, `Дата: ${today()}`]));
  c.push(sp(160));

  c.push(P([R("Настоящий акт составлен во исполнение договора об отчуждении исключительного права на программу для ЭВМ "),
    B(val(p.name)), R(" от «__» ________ 20__ г.")]));
  c.push(sp());
  c.push(tbl([3400, 5960], ["Параметр", "Значение"], [
    ["Программа", val(p.name)],
    ["Основание права Автора", certLine(r)],
    ["Автор (передающая сторона)", val(a.fullName)],
    ["Приобретатель", `${val(rh.orgName)} (ИНН ${val(rh.inn)}, ОГРН ${val(rh.ogrn)})`],
  ]));
  c.push(sp());
  c.push(bullet("Автор передал, а Приобретатель принял исключительное право на Программу в полном объёме."));
  c.push(bullet("Переданы экземпляр Программы и материалы, идентифицирующие её (реферат, снимок кода)."));
  c.push(bullet("Стороны претензий друг к другу не имеют. Исключительное право принадлежит Приобретателю."));
  c.push(sp(240));

  c.push(tbl([4680, 4680], ["Передал (Автор)", "Принял (Приобретатель)"], [
    [`${val(a.fullName)}\n\n_______________ / подпись`,
     `${val(rh.orgName)}\n${rh.signatory && rh.signatory.name ? rh.signatory.name : "___________________"}\n\n_______________ / М.П.`],
  ]));
  c.push(sp());
  c.push(note("Что это даёт", [R("Договор + акт замыкают цепочку прав автор→ООО. С этого момента правообладателем для реестра Минцифры выступает организация.")]));
  return c;
}

// ---------- Заявление о регистрации отчуждения (перехода) права в ФИПС ----------
// ст. 1232 п.2, ст. 1262 п.5 ГК РФ: переход исключительного права на зарегистрированную
// в Роспатенте программу подлежит госрегистрации в ФИПС. Без неё переход считается
// несостоявшимся (ст.1232 п.6) → реестр Минцифры завернёт цепочку прав.
function docRegisterTransfer(pr, ctx = {}) {
  const p = pr.product || {}, rh = pr.rightholder || {}, r = pr.rights || {};
  const a = ctx.author || {};
  const c = [];
  c.push(...titleBlock("ЗАЯВЛЕНИЕ",
    "о государственной регистрации отчуждения (перехода) исключительного права на программу для ЭВМ",
    [`Программа: ${val(p.name)}`, `В: ФИПС (Роспатент)`, `Дата: ${today()}`]));
  c.push(sp(160));

  c.push(P([R("В соответствии со ст. 1232 (п. 2) и ст. 1262 (п. 5) ГК РФ прошу зарегистрировать "
    + "переход исключительного права на программу для ЭВМ на основании договора об отчуждении "
    + "исключительного права.")]));
  c.push(sp());

  c.push(H1("1. Зарегистрированная программа для ЭВМ"));
  c.push(tbl([3400, 5960], ["Параметр", "Значение"], [
    ["Наименование программы", val(p.name)],
    ["Свидетельство о госрегистрации ПрЭВМ", `№ ${val(r.rospatentCertificateNumber)} от ${val(r.rospatentCertificateDate)}`],
  ]));
  c.push(sp());

  c.push(H1("2. Стороны договора об отчуждении"));
  c.push(tbl([3400, 5960], ["Роль", "Сведения"], [
    ["Правообладатель (отчуждатель) — автор-физлицо",
      `${val(a.fullName)}${a.snils ? `, СНИЛС ${a.snils}` : ""}${a.address ? `, адрес: ${a.address}` : ""}`],
    ["Приобретатель — правообладатель (ООО)",
      `${val(rh.orgName)} (ОГРН ${val(rh.ogrn)}, ИНН ${val(rh.inn)}, адрес: ${val(rh.address)})`],
  ]));
  c.push(sp());

  c.push(H1("3. Основание перехода права"));
  c.push(P([R("Договор об отчуждении исключительного права на программу для ЭВМ "),
    B(val(p.name)), R(" от «__» ________ 20__ г. (ст. 1234 ГК РФ), акт приёма-передачи от той же даты.")]));
  c.push(sp());

  c.push(H1("4. Приложения"));
  c.push(bullet("Договор об отчуждении исключительного права (экземпляр или выписка по ст. 1234 ГК)."));
  c.push(bullet("Документ об уплате государственной пошлины за регистрацию распоряжения правом (СВЕРИТЬ тариф на fips.ru)."));
  c.push(bullet("Согласие сторон на обработку и публикацию сведений о регистрации распоряжения правом."));
  c.push(sp());

  c.push(P([R("Заявитель: "),
    R(rh.signatory && rh.signatory.name ? `${rh.signatory.position || "руководитель"} ${rh.signatory.name}` : "уполномоченное лицо приобретателя"),
    R(". Подпись — УКЭП организации-приобретателя.")]));
  c.push(sp(240));

  c.push(tbl([4680, 4680], ["Отчуждатель (Автор)", "Приобретатель (ООО)"], [
    [`${val(a.fullName)}\n\n_______________ / подпись`,
     `${val(rh.orgName)}\n${rh.signatory && rh.signatory.name ? rh.signatory.name : "___________________"}\n\n_______________ / М.П.`],
  ]));
  c.push(sp());
  c.push(note("Почему это обязательно", [
    R("Раз программа прошла госрегистрацию в Роспатенте, переход права по договору отчуждения "),
    R("тоже подлежит госрегистрации в ФИПС (ст. 1232 п. 2, ст. 1262 п. 5 ГК). Без неё переход "),
    B("считается несостоявшимся"), R(" (ст. 1232 п. 6) — и реестр Минцифры завернёт цепочку прав. "),
    R("Каркас заявления; форму и пошлину сверить на fips.ru, подписать у юриста правообладателя."),
  ]));
  return c;
}

function listAssignmentDocs() {
  return [
    { kind: "dep_assign_contract", title: "Договор отчуждения права", file: "Договор_отчуждения", make: docContract, needsCert: true },
    { kind: "dep_assign_act", title: "Акт приёма-передачи", file: "Акт_приёма-передачи", make: docAct, needsCert: true },
    { kind: "dep_assign_register", title: "Заявление о регистрации отчуждения (ФИПС)", file: "Заявление_регистрация_отчуждения", make: docRegisterTransfer, needsCert: true },
  ];
}

async function buildAssignmentDoc(kind, product, ctx = {}) {
  const def = listAssignmentDocs().find((d) => d.kind === kind);
  if (!def) throw new Error(`Неизвестный документ отчуждения: ${kind}`);
  const short = safeFileName((product.product && product.product.shortName) || "product");
  const fileName = `${def.file}_${short}.docx`;
  const children = def.make(product, ctx);
  const buffer = await buildBuffer(children, { title: def.title, header: `${def.title} · ${short}` });
  return { fileName, buffer, title: def.title };
}

module.exports = { listAssignmentDocs, buildAssignmentDoc, today };
