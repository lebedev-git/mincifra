// ---------- Документ 2: Бухгалтерская справка < 30% ----------
function docFinance(pr) {
  const p = pr.product, rh = pr.rightholder, f = pr.finance;
  const ratio = f.annualForeignPayments / f.annualRevenueProduct;
  const pct = (ratio * 100).toFixed(2);
  const c = [];
  c.push(...titleBlock("БУХГАЛТЕРСКАЯ СПРАВКА",
    "о доле выплат иностранным правообладателям", [`Дата: ${today()}`]));
  c.push(sp(200));
  c.push(P([R("Настоящая справка подтверждает, что за отчётный период сумма выплат по лицензионным и иным договорам в пользу иностранных правообладателей за права на программное обеспечение "),
    B(p.name), R(" и его компоненты составляет менее 30% выручки правообладателя "),
    B(`${rh.orgName} (ИНН ${rh.inn})`), R(" от реализации указанного ПО.")]));
  c.push(sp());
  c.push(tbl([5600, 3760], ["Показатель", `Значение, ${f.currency}`], [
    ["Выручка от реализации ПО за период", fmtMoney(f.annualRevenueProduct)],
    ["Выплаты иностранным правообладателям за права на ПО и компоненты", fmtMoney(f.annualForeignPayments)],
    [new H.docx.Paragraph({ children: [B("Доля выплат в выручке")] }),
     new H.docx.Paragraph({ children: [new H.docx.TextRun({ text: `${pct}%`, bold: true })] })],
    ["Нормативный порог (ПП РФ № 1236)", "строго < 30%"],
  ]));
  c.push(sp());
  c.push(P([B("Вывод: "), R(ratio < 0.30
    ? `критерий соблюдён (${pct}% < 30%).`
    : `критерий НЕ соблюдён (${pct}% >= 30%) — включение невозможно до устранения.`)]));
  c.push(sp(240));
  c.push(P([R("Главный бухгалтер / уполномоченное лицо: _______________________ / ___________________")]));
  c.push(P([R("Руководитель: "), B(rh.signatory ? rh.signatory.name : "_______________"), R("  М.П.")]));
  c.push(sp());
  c.push(note("Основание",
    [R("Финансовый критерий ПП РФ № 1236: годовые выплаты иностранным лицам за права на ПО и его компоненты — строго менее 30% выручки правообладателя по этому ПО. Значения подставлены из product.json; подтверждаются первичными документами бухгалтерии.")]));
  return c;
}

