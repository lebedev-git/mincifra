"use strict";
// Чистая логика генерации пакета досье (без CLI-эффектов).
// Используется CLI-обёрткой gen_dossier.js и веб-платформой (platform/).
//
// listDocuments(short) -> [{ name, title, make }]   — состав пакета
// buildDossier(product, outDir, onDoc?) -> Promise<[{ name, bytes, path }]>
//
// ВНИМАНИЕ: правовые формулировки — шаблонные каркасы, требуют проверки
// юристом/бухгалтером правообладателя. Пороги/сроки помечены «СВЕРИТЬ».

const fs = require("fs");
const path = require("path");
const H = require("./lib/docx_helpers");
const { H1, P, bullet, R, B, sp, pageBreak, note, tbl, titleBlock, build } = H;

// Убирает символы, недопустимые в именах файлов Windows (< > : " / \ | ? *),
// иначе двоеточие в имени продукта уводит запись в скрытый ADS-поток NTFS.
function safeFileName(s) {
  return String(s || "").replace(/[<>:"/\\|?*\x00-\x1F]/g, "").replace(/\s+/g, " ").trim();
}

function fmtMoney(n) { return new Intl.NumberFormat("ru-RU").format(n); }
function today() {
  const d = new Date();
  return `${String(d.getDate()).padStart(2, "0")}.${String(d.getMonth() + 1).padStart(2, "0")}.${d.getFullYear()}`;
}

